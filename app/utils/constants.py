def label_by_code(options: Iterable[tuple], code: str) -> Optional[str]:
    """Вернуть подпись по коду из справочника вида (код, подпись, ...)."""
    for item in options:
        if item[0] == code:
            return item[1]
    return None


def code_by_label(options: Iterable[tuple], label: str) -> Optional[str]:
    """Вернуть код по подписи из справочника вида (код, подпись, ...)."""
    for item in options:
        if item[1] == label:
            return item[0]
    return None
